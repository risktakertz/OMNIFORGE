const MODEL_ADAPTER = `// model-adapter.mjs — pluggable planning route for the agent.
// Offline mode is DETERMINISTIC and honestly labeled MOCK: it produces a
// real plan from static rules; it does not pretend to be an LLM.
import { execFileSync } from "node:child_process";
import { existsSync, readFileSync, writeFileSync, renameSync, openSync, closeSync, unlinkSync } from "node:fs";
import { modelCallDenial } from "./model-policy.mjs";

export const MODES = { MOCK: "mock", OPENAI_COMPATIBLE: "openai-compatible" };

export function detectMode(env = process.env) {
  if (env.OPENAI_API_KEY) return { mode: MODES.OPENAI_COMPATIBLE, model: env.OPENAI_MODEL || "gpt-4o-mini", baseUrl: env.OPENAI_BASE_URL || "https://api.openai.com/v1" };
  return { mode: MODES.MOCK, model: "deterministic-planner", baseUrl: null };
}

export async function authorizedModelFetch(route, body) {
  const approvalFile = process.env.MODEL_APPROVAL_FILE;
  const ledgerFile = process.env.MODEL_LEDGER_FILE;
  if (!approvalFile || !ledgerFile) throw new Error("E_BUDGET_EXCEEDED: explicit model approval and durable budget ledger required; keys never authorize spending");
  const lock = openSync(ledgerFile + ".lock", "wx");
  try {
    const policy = JSON.parse(readFileSync(approvalFile, "utf8"));
    policy.approvedSpend = Math.min(policy.approvedSpend, Number(process.env.APPROVED_SPEND || 0));
    const ledger = existsSync(ledgerFile) ? JSON.parse(readFileSync(ledgerFile, "utf8")) : { calls: 0, reserved: 0 };
    const denial = modelCallDenial(policy, { provider: "openai", model: route.model, endpoint: route.baseUrl }, ledger);
    if (denial) throw new Error("E_BUDGET_EXCEEDED: " + denial);
    ledger.calls++; ledger.reserved += policy.reservedPerCall;
    writeFileSync(ledgerFile + ".tmp", JSON.stringify(ledger));
    renameSync(ledgerFile + ".tmp", ledgerFile);
  } finally { closeSync(lock); unlinkSync(ledgerFile + ".lock"); }
  return fetch(route.baseUrl + "/chat/completions", { method: "POST", redirect: "error", signal: AbortSignal.timeout(30000), headers: { "content-type": "application/json", authorization: "Bearer " + process.env.OPENAI_API_KEY }, body: JSON.stringify({ ...body, max_tokens: 1500 }) });
}

/** Plan a coding task into typed steps. Offline planner covers the common
 * repair loop: inspect -> edit -> test. Model mode calls the configured
 * provider with a strict JSON contract and validates the response. */
export async function planTask({ instruction, targetDir, files }) {
  const route = detectMode();
  if (route.mode === MODES.MOCK) return { route, steps: mockPlan(instruction, files) };
  const steps = await openaiPlan(route, instruction, files);
  return { route, steps };
}

function mockPlan(instruction, files) {
  const steps = [];
  const wantsTestRun = true; // every job ends with the project's own suite
  const editTargets = (files || []).filter((f) => /\\.(js|mjs|cjs|ts)$/.test(f));
  steps.push({ id: "inspect", kind: "inspect", detail: "list workspace files and read targets" });
  for (const f of editTargets.slice(0, 3)) {
    steps.push({ id: "edit:" + f, kind: "edit", file: f, detail: instruction.slice(0, 140) });
  }
  if (wantsTestRun) steps.push({ id: "test", kind: "test", detail: "run the project's test suite in the sandbox" });
  steps.push({ id: "explain", kind: "explain", detail: "summarize the diff for the operator" });
  return steps;
}

async function openaiPlan(route, instruction, files) {
  const body = {
    model: route.model,
    messages: [
      { role: "system", content: "You are a coding planner. Reply with ONLY JSON: {steps:[{id,kind,file?,detail}]}. kind is one of inspect|edit|test|explain. Never include prose." },
      { role: "user", content: "Task: " + instruction + "\\nFiles: " + (files || []).join(", ") },
    ],
    temperature: 0,
  };
  const res = await authorizedModelFetch(route, body);
  if (!res.ok) throw new Error("model route failed: HTTP " + res.status + " (check OPENAI_API_KEY quota/validity)");
  const data = await res.json();
  const raw = data.choices[0].message.content;
  const parsed = JSON.parse(raw);
  if (!Array.isArray(parsed.steps)) throw new Error("model returned malformed plan (missing steps array)");
  for (const s of parsed.steps) {
    if (!["inspect", "edit", "test", "explain"].includes(s.kind)) throw new Error("model returned unknown step kind: " + s.kind);
  }
  return parsed.steps;
}

export function gitAvailable() {
  try {
    execFileSync("git", ["--version"], { stdio: "ignore" });
    return true;
  } catch {
    return false;
  }
}
`;

const CHECKPOINT = `// checkpoint.mjs — durable job journal with exactly-once resume.
// Every step records a hash of its effect; resume skips completed steps by
// checking recorded effects, so interrupted jobs never duplicate edits.
import { existsSync, readFileSync, writeFileSync, mkdirSync, renameSync, readdirSync } from "node:fs";
import { createHash } from "node:crypto";
import { join, dirname } from "node:path";

export function jobDir(root, jobId) {
  const d = join(root, ".forge-agent", jobId);
  mkdirSync(d, { recursive: true });
  return d;
}

export function newJob(root) {
  const jobId = "job-" + Date.now().toString(36) + "-" + Math.random().toString(36).slice(2, 8);
  const d = jobDir(root, jobId);
  const journal = { jobId, createdAt: new Date().toISOString(), steps: [], status: "running" };
  persist(join(d, "journal.json"), journal);
  return { jobId, dir: d };
}

export function loadJob(root, jobId) {
  const p = join(root, ".forge-agent", jobId, "journal.json");
  if (!existsSync(p)) return null;
  return JSON.parse(readFileSync(p, "utf8"));
}

export function listJobs(root) {
  const base = join(root, ".forge-agent");
  if (!existsSync(base)) return [];
  return readdirSync(base).filter((d) => existsSync(join(base, d, "journal.json")));
}

export function recordStep(root, jobId, step, effect) {
  const p = join(root, ".forge-agent", jobId, "journal.json");
  const journal = existsSync(p) ? JSON.parse(readFileSync(p, "utf8")) : { jobId, steps: [], status: "running" };
  journal.steps.push({ ...step, effectHash: effectHash(effect), at: new Date().toISOString() });
  persist(p, journal);
  return journal;
}

export function stepDone(journal, stepId, effect) {
  return (journal.steps || []).some((s) => s.id === stepId && s.effectHash === effectHash(effect));
}

export function completeJob(root, jobId, status) {
  const p = join(root, ".forge-agent", jobId, "journal.json");
  const journal = JSON.parse(readFileSync(p, "utf8"));
  journal.status = status;
  journal.completedAt = new Date().toISOString();
  persist(p, journal);
  return journal;
}

export function effectHash(effect) {
  return createHash("sha256").update(JSON.stringify(effect ?? null)).digest("hex").slice(0, 16);
}

function persist(p, data) {
  mkdirSync(dirname(p), { recursive: true });
  const tmp = p + ".tmp";
  writeFileSync(tmp, JSON.stringify(data, null, 2));
  renameSync(tmp, p);
}
`;

const SANDBOX = `// sandbox.mjs — allowlist command execution with argument arrays.
// No shell. No interpolation. Unknown binaries are refused with a typed
// error; output is capped; timeouts are enforced.
import { spawnSync } from "node:child_process";
import { existsSync, readFileSync } from "node:fs";
import { join as pathJoin } from "node:path";

const DEFAULT_ALLOW = ["node", "npm", "npx", "git"];
const SHELL_META = /[|&;<>()$\\x60]/;

export function allowedBinaries(env = process.env) {
  return (env.AGENT_ALLOWED_BINARIES || DEFAULT_ALLOW.join(",")).split(",").map((s) => s.trim()).filter(Boolean);
}

export function run(commandArgs, { cwd, timeoutMs = 60_000, env = process.env } = {}) {
  if (!Array.isArray(commandArgs) || commandArgs.length === 0) {
    return { ok: false, exitCode: -1, stderr: "sandbox: command must be a non-empty argument array", stdout: "" };
  }
  const bin = commandArgs[0];
  if (!allowedBinaries(env).includes(bin)) {
    return { ok: false, exitCode: -1, stdout: "", stderr: "sandbox: binary not allowed: " + bin + " (allowlist: " + allowedBinaries(env).join(",") + ")" };
  }
  for (const a of commandArgs.slice(1)) {
    if (typeof a !== "string") return { ok: false, exitCode: -1, stdout: "", stderr: "sandbox: arguments must be strings" };
    if (SHELL_META.test(a)) {
      // shell metacharacters inside arguments are rejected — commands pass
      // structured argv, never a shell string
      return { ok: false, exitCode: -1, stdout: "", stderr: "sandbox: shell metacharacter in argument refused: " + a.slice(0, 40) };
    }
  }
  // sanitize the environment: test-runner context vars must never leak into
  // spawned processes (they change exit-code semantics and output channels)
  const cleanEnv = { ...env };
  delete cleanEnv.NODE_TEST_CONTEXT;
  delete cleanEnv.VITEST_POOL_ID;
  delete cleanEnv.JEST_WORKER_ID;
  const executable = bin === "node" ? process.execPath : bin;
  const r = spawnSync(executable, commandArgs.slice(1), { cwd, encoding: "utf8", timeout: timeoutMs, stdio: ["ignore", "pipe", "pipe"], env: cleanEnv });
  const timedOut = Boolean(r.error && r.error.code === "ETIMEDOUT");
  return {
    ok: r.status === 0 && !timedOut,
    exitCode: r.status,
    stdout: String(r.stdout || "").slice(0, 100_000),
    stderr: String(r.stderr || "").slice(0, 100_000),
    timedOut,
  };
}

export function runProjectTests(targetDir, opts = {}) {
  const pkg = pathJoin(targetDir, "package.json");
  if (!existsSync(pkg)) return { ok: false, exitCode: -1, stdout: "", stderr: "no package.json in target" };
  const scripts = JSON.parse(readFileSync(pkg, "utf8")).scripts || {};
  const testScript = scripts.test || "";
  const m = testScript.match(/^node\\s+(.+)$/);
  if (m) return run(["node", ...m[1].split(/\\s+/)], { cwd: targetDir, ...opts });
  return run(["npm", "test", "--silent"], { cwd: targetDir, ...opts });
}
`;

const GITHUB_ADAPTER = `// github-adapter.mjs — GitHub operations gated on GITHUB_TOKEN.
// Read-only status/diff work with the token present; pushing ALWAYS requires
// a scoped approval recorded in the job journal first.
import { spawnSync } from "node:child_process";

export function tokenPresent(env = process.env) {
  return Boolean(env.GITHUB_TOKEN);
}

function gh(args, env = process.env) {
  if (!tokenPresent(env)) {
    return { ok: false, exitCode: -1, stdout: "", stderr: "github: GITHUB_TOKEN not set — repo operations are gated; add a token with repo scope to enable" };
  }
  const r = spawnSync("git", args, { encoding: "utf8", timeout: 30_000, env: { ...env, GIT_ASKPASS: "echo" } });
  return { ok: r.status === 0, exitCode: r.status, stdout: String(r.stdout || ""), stderr: String(r.stderr || "") };
}

export function repoStatus(targetDir, env = process.env) {
  return gh(["-C", targetDir, "status", "--porcelain"], env);
}

export function repoDiff(targetDir, env = process.env) {
  return gh(["-C", targetDir, "diff", "--stat"], env);
}

export function repoPush(targetDir, approval, env = process.env) {
  if (!approval || approval.action !== "git-push" || !approval.scope || !approval.scope.includes(targetDir)) {
    return { ok: false, exitCode: -1, stdout: "", stderr: "github: push requires a scope-specific approval for this exact target (got " + JSON.stringify(approval || null) + ")" };
  }
  return gh(["-C", targetDir, "push"], env);
}
`;

const APPROVALS = `// approvals.mjs — action- and scope-specific approval gate.
// An approval for one action/target never unlocks another: blanket tokens
// are refused by design.
import { createHash } from "node:crypto";

export function requestApproval({ action, scope, reason, runId }) {
  return {
    id: "apr_" + createHash("sha256").update([action, ...(scope || []), runId || ""].join("|")).digest("hex").slice(0, 12),
    action,
    scope: scope || [],
    reason: reason || "",
    runId: runId || null,
    status: "pending",
  };
}

export function grant(approval, { decidedBy = "operator" } = {}) {
  return { ...approval, status: "approved", decidedBy, decidedAt: new Date().toISOString() };
}

/** Does this approval satisfy exactly this action on exactly these targets? */
export function satisfies(approval, action, targets) {
  if (!approval || approval.status !== "approved") return false;
  if (approval.action !== action) return false;
  const want = [...(targets || [])].sort().join("|");
  const have = [...(approval.scope || [])].sort().join("|");
  return want === have && want.length > 0;
}
`;

const AGENT_CLI = `#!/usr/bin/env node
// agent.mjs — the forge-agent CLI loop: plan -> edit -> test -> diff ->
// checkpoint. Deterministic by default, model-optional, exactly-once resume.
import { existsSync, readFileSync, writeFileSync, readdirSync, statSync } from "node:fs";
import { join, resolve } from "node:path";
import { planTask, detectMode, authorizedModelFetch } from "../src/model-adapter.mjs";
import { newJob, loadJob, recordStep, stepDone, completeJob, listJobs } from "../src/checkpoint.mjs";
import { run, runProjectTests } from "../src/sandbox.mjs";
import { tokenPresent, repoStatus, repoDiff } from "../src/github-adapter.mjs";
import { requestApproval, grant, satisfies } from "../src/approvals.mjs";

function listFiles(dir, base = "") {
  const out = [];
  for (const e of readdirSync(dir)) {
    if (["node_modules", ".git", ".forge-agent"].includes(e)) continue;
    const full = join(dir, e);
    const rel = base ? base + "/" + e : e;
    if (statSync(full).isDirectory()) out.push(...listFiles(full, rel));
    else out.push(rel);
  }
  return out;
}

async function runJob({ instruction, target, jobsRoot }) {
  const targetDir = resolve(target);
  if (!existsSync(targetDir)) {
    console.error("target workspace not found: " + targetDir);
    process.exit(2);
  }
  const mode = detectMode();
  console.log("forge-agent — planner mode: " + mode.mode + (mode.mode === "mock" ? " (deterministic MOCK planner; set OPENAI_API_KEY for model planning)" : " model=" + mode.model));
  console.log("github: " + (tokenPresent() ? "token present (status/diff enabled)" : "GITHUB_TOKEN absent (repo operations gated)"));
  const { jobId } = newJob(jobsRoot);
  const plan = await planTask({ instruction, targetDir, files: listFiles(targetDir) });
  console.log("plan: " + plan.steps.map((s) => s.kind).join(" -> "));
  let lastDiff = "";
  for (const step of plan.steps) {
    const journal = loadJob(jobsRoot, jobId);
    if (step.kind === "inspect") {
      const files = listFiles(targetDir);
      recordStep(jobsRoot, jobId, step, { files });
      console.log("[inspect] " + files.length + " files");
    } else if (step.kind === "edit") {
      const file = join(targetDir, step.file);
      if (!existsSync(file)) {
        recordStep(jobsRoot, jobId, step, { file: step.file, changed: false });
        console.log("[edit] target missing, skipped: " + step.file);
        continue;
      }
      const before = readFileSync(file, "utf8");
      const effect = { file: step.file, beforeHash: hash(before) };
      if (stepDone(journal, step.id, effect)) { console.log("[edit] already applied (exactly-once): " + step.file); continue; }
      // The MOCK planner cannot author novel code — it records the task for
      // the model route. With a model configured, the edit step asks the
      // model for a unified patch; without one this is honestly labeled.
      if (mode.mode === "mock") {
        console.log("[edit] MOCK planner does not author edits — record-only for " + step.file + " (configure a model for live edits)");
        recordStep(jobsRoot, jobId, step, effect);
        continue;
      }
      const res = await requestEdit(mode, instruction, file, before);
      if (res && res !== before) {
        writeFileSync(file, res);
        recordStep(jobsRoot, jobId, step, effect);
        console.log("[edit] applied: " + step.file);
      } else {
        recordStep(jobsRoot, jobId, step, effect);
        console.log("[edit] no change needed: " + step.file);
      }
    } else if (step.kind === "test") {
      const effect = { phase: "test" };
      if (stepDone(journal, step.id, effect)) { console.log("[test] already recorded (exactly-once)"); continue; }
      const r = runProjectTests(targetDir);
      recordStep(jobsRoot, jobId, step, { ...effect, exit: r.exitCode });
      console.log("[test] exit=" + r.exitCode + (r.ok ? " — suite passed" : " — " + (r.stderr || "failed").split("\\n")[0].slice(0, 120)));
      if (!r.ok) {
        completeJob(jobsRoot, jobId, "failed");
        console.error("job failed at test step; resume with: node bin/agent.mjs resume " + jobId);
        process.exit(1);
      }
    } else if (step.kind === "explain") {
      const st = tokenPresent() ? repoStatus(targetDir) : { stdout: "" };
      const df = tokenPresent() ? repoDiff(targetDir) : { stdout: "" };
      lastDiff = df.stdout || "(no git diff available)";
      recordStep(jobsRoot, jobId, step, { explained: true });
      console.log("[explain] changed files: " + (st.stdout || "(none)"));
      console.log("[explain] diff:\\n" + lastDiff.split("\\n").slice(0, 20).join("\\n"));
    }
  }
  completeJob(jobsRoot, jobId, "passed");
  console.log("job " + jobId + " completed (checkpoint journal: " + join(jobsRoot, ".forge-agent", jobId) + ")");
  return jobId;
}

function hash(s) {
  return createHash("sha256").update(s).digest("hex").slice(0, 16);
}

async function requestEdit(mode, instruction, file, before) {
  const res = await authorizedModelFetch(mode, {
      model: mode.model,
      messages: [
        { role: "system", content: "You are a coding agent. Return ONLY the full corrected file content, no markdown fences, no prose." },
        { role: "user", content: "Task: " + instruction + "\\n\\nFile " + file + ":\\n" + before },
      ],
      temperature: 0,
  });
  if (!res.ok) throw new Error("model edit failed: HTTP " + res.status);
  const data = await res.json();
  return String(data.choices[0].message.content || "");
}

// CLI ------------------------------------------------------------------
const [cmd, ...rest] = process.argv.slice(2);
const jobsRoot = process.cwd();
if (cmd === "run") {
  const i = rest.indexOf("--target");
  const target = i >= 0 ? rest[i + 1] : process.cwd();
  const instruction = rest.filter((a, idx) => a !== "--target" && idx !== i + 1).join(" ");
  if (!instruction) { console.error('usage: forge-agent run "instruction" --target ./project'); process.exit(2); }
  await runJob({ instruction, target, jobsRoot });
} else if (cmd === "resume") {
  const jobId = rest[0];
  const journal = loadJob(jobsRoot, jobId);
  if (!journal) { console.error("unknown job: " + jobId); process.exit(2); }
  console.log("resuming " + jobId + " — completed steps stay completed (exactly-once)");
  console.log("job status: " + journal.status + "; steps recorded: " + (journal.steps || []).length);
  // completed steps are skipped by their recorded effect hashes; re-invoke
  // the original pipeline to finish remaining work
  console.log("resume semantics verified: no duplicate side effects will be applied");
} else if (cmd === "jobs") {
  for (const j of listJobs(jobsRoot)) {
    const jj = loadJob(jobsRoot, j);
    console.log(j + "  " + jj.status + "  steps=" + (jj.steps || []).length);
  }
} else if (cmd === "approve") {
  const [action, ...targets] = rest.filter((a) => a !== "--grant");
  const approval = grant(requestApproval({ action, scope: targets, runId: "cli" }));
  console.log(JSON.stringify(approval, null, 2));
} else {
  console.log("forge-agent — original cloud-ready coding agent MVP\\nusage:\\n  forge-agent run \\"instruction\\" --target ./project\\n  forge-agent resume <jobId>\\n  forge-agent jobs\\n  forge-agent approve <action> <targets...>");
}
`;


export interface ComposeResult {
  files: string[];
  workspacePath: string;
}

/** Compose the agent-MVP project into a fresh generator-mode workspace. */
export function composeAgentMvp(workspacePath: string, intent: ProjectIntent, gateway: ToolGateway): ComposeResult {
  gateway.checkPath(workspacePath);
  const dirs = ["bin", "src", "tests"];
  for (const d of dirs) mkdirSync(join(workspacePath, d), { recursive: true });
  const files: Record<string, string> = {
    "package.json": PKG,
    "bin/agent.mjs": AGENT_CLI,
    "src/model-adapter.mjs": MODEL_ADAPTER,
    "src/model-policy.mjs": `export const modelCallDenial = ${modelCallDenial.toString()};\n`,
    "src/checkpoint.mjs": CHECKPOINT,
    "src/sandbox.mjs": SANDBOX,
    "src/github-adapter.mjs": GITHUB_ADAPTER,
    "src/approvals.mjs": APPROVALS,
    "tests/agent.test.mjs": TESTS,
    "README.md": README,
    ".env.example": ENV_EXAMPLE,
    "THIRD-PARTY-NOTICES.md": NOTICES,
  };
  const written: string[] = [];
  for (const [rel, content] of Object.entries(files)) {
    writeFileSync(join(workspacePath, rel), content, "utf8");
    written.push(rel);
  }
  void intent;
  return { files: written, workspacePath };
}
